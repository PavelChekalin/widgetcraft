def load_known_names() -> set:
    """Список файлов набора (tools/lucide_names.txt), чтобы не дёргать сеть зря."""
    if not os.path.exists(NAMES_FILE):
        return set()
    with open(NAMES_FILE, encoding="utf-8") as handle:
        return {line.strip() for line in handle if line.strip()}


def normalize_path_data(d):
    """Приводит pathData к виду, который понимает Android.

    Lucide пишет дуги компактно («a3 2.5 0 016 0»): флаги largeArc/sweep идут
    слитно с числами. Android такой разбор не осиливает и падает при инфляции.
    """
    out = []
    i = 0
    n = len(d)

    def skip_sep():
        nonlocal i
        while i < n and d[i] in " ,\t\r\n":
            i += 1

    number_re = re.compile(r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?")

    def read_number():
        nonlocal i
        match = number_re.match(d, i)
        if not match:
            i += 1
            return ""
        i = match.end()
        return match.group(0)

    def read_flag():
        nonlocal i
        char = d[i]
        i += 1
        return char

    current = ""
    while i < n:
        skip_sep()
        if i >= n:
            break
        char = d[i]
        if char.isalpha():
            current = char
            out.append(char)
            i += 1
            continue
        if current.lower() == "a":
            rx = read_number()
            skip_sep()
            ry = read_number()
            skip_sep()
            rotation = read_number()
            skip_sep()
            large_arc = read_flag()
            skip_sep()
            sweep = read_flag()
            skip_sep()
            x = read_number()
            skip_sep()
            y = read_number()
            out.append(f"{rx},{ry} {rotation} {large_arc},{sweep} {x},{y}")
        else:
            out.append(read_number())

    return " ".join(out)


def convert_svg(svg_text):
    """SVG Lucide -> vector drawable. Поддержаны path/line/circle/rect/polyline/polygon."""
    body = svg_text.split(">", 1)[1] if svg_text.strip().startswith("<svg") else svg_text
    stroke_width = re.search(r'stroke-width="([\d.]+)"', svg_text)
    width = stroke_width.group(1) if stroke_width else "2"

    def num(value):
        value = value.replace("px", "").strip()
        return value.rstrip("0").rstrip(".") if "." in value else value

    parts = []

    for match in re.finditer(r"<(path|line|circle|rect|polyline|polygon)\b([^>]*)/?>", body):
        tag, attrs = match.group(1), match.group(2)

        def attr(name, default="0"):
            found = re.search(rf'{name}="([^"]*)"', attrs)
            return found.group(1) if found else default

        if tag == "path":
            data = attr("d")
            if not data:
                continue
        elif tag == "line":
            data = "M{0},{1} L{2},{3}".format(
                num(attr("x1")), num(attr("y1")), num(attr("x2")), num(attr("y2"))
            )
        elif tag == "circle":
            cx, cy, r = num(attr("cx")), num(attr("cy")), num(attr("r"))
            data = (
                f"M{cx},{cy} m-{r},0 a{r},{r} 0 1,0 {float(r) * 2:g},0 "
                f"a{r},{r} 0 1,0 -{float(r) * 2:g},0"
            )
        elif tag == "rect":
            x, y = float(attr("x")), float(attr("y"))
            w, h = float(attr("width")), float(attr("height"))
            r = float(attr("rx", "0"))
            if r > 0:
                data = (
                    f"M{x + r},{y} h{w - 2 * r} a{r},{r} 0 0 1 {r},{r} v{h - 2 * r} "
                    f"a{r},{r} 0 0 1 -{r},{r} h-{w - 2 * r} a{r},{r} 0 0 1 -{r},-{r} "
                    f"v-{h - 2 * r} a{r},{r} 0 0 1 {r},-{r} z"
                )
            else:
                data = f"M{x},{y} h{w} v{h} h-{w} z"
        else:
            points = [p for p in re.split(r"[\s,]+", attr("points")) if p]
            if not points:
                continue
            pairs = list(zip(points[0::2], points[1::2]))
            data = "M" + " L".join(f"{num(a)},{num(b)}" for a, b in pairs)
            if tag == "polygon":
                data += " z"

        parts.append(
            '    <path\n'
            f'        android:pathData="{normalize_path_data(data)}"\n'
            '        android:strokeColor="#FFFFFFFF"\n'
            f'        android:strokeWidth="{width}"\n'
            '        android:strokeLineCap="round"\n'
            '        android:strokeLineJoin="round" />'
        )

    if not parts:
        return ""

    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Lucide (MIT). Сгенерировано tools/build_icons.py, руками не править. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        '    android:viewportWidth="24"\n'
        '    android:viewportHeight="24">\n'
        + "\n".join(parts)
        + "\n</vector>\n"
    )


def main():
    os.makedirs(DRAWABLE_DIR, exist_ok=True)
    os.makedirs(ASSETS_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)

    known = load_known_names()
    index = []
    failed = []

    for name, ru, category, keywords in ICONS:
        if known and name not in known:
            failed.append((name, "нет в наборе"))
            continue
        try:
            cache_path = os.path.join(CACHE_DIR, name + ".svg")
            if os.path.exists(cache_path):
                with open(cache_path, encoding="utf-8") as handle:
                    svg = handle.read()
            else:
                svg = ""
                for attempt in range(3):
                    try:
                        with urllib.request.urlopen(BASE_URL.format(name=name), timeout=20) as response:
                            svg = response.read().decode("utf-8")
                        break
                    except Exception:
                        # Сеть до CDN иногда рвётся на середине — три попытки дешевле ручного перезапуска.
                        if attempt == 2:
                            raise
                        time.sleep(0.8)
                with open(cache_path, "w", encoding="utf-8") as handle:
                    handle.write(svg)

            vector = convert_svg(svg)
            if not vector:
                failed.append((name, "не найдено фигур"))
                continue

            file_name = PREFIX + name.replace("-", "_")
            with open(os.path.join(DRAWABLE_DIR, file_name + ".xml"), "w", encoding="utf-8") as out:
                out.write(vector)
            index.append({
                "file": file_name,
                "name": ru,
                "category": category,
                "keywords": keywords,
            })
        except Exception as error:
            failed.append((name, str(error)))
        time.sleep(0.02)

    index.sort(key=lambda item: (item["category"], item["name"]))

    # Убираем файлы прошлых запусков: имена иконок меняются, мусор в res не нужен.
    keep = {item["file"] + ".xml" for item in index}
    for file_name in os.listdir(DRAWABLE_DIR):
        if file_name.startswith(PREFIX) and file_name not in keep:
            os.remove(os.path.join(DRAWABLE_DIR, file_name))

    with open(os.path.join(ASSETS_DIR, "icons.json"), "w", encoding="utf-8") as out:
        json.dump(index, out, ensure_ascii=False, indent=1)

    print("готово иконок:", len(index))
    if failed:
        print("не удалось:", len(failed))
        for name, reason in failed:
            print("  -", name, ":", reason)
    return 0 if index else 1


if __name__ == "__main__":
    sys.exit(main())
